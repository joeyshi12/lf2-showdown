#!/usr/bin/env python3
"""Write docs/function-map.md from re/out/functions.tsv (Ghidra export) and
re/names.tsv (names, confidence, status, description)."""
import os
ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..")
fn = {}
for l in open(os.path.join(ROOT, "re/out/functions.tsv")).read().splitlines()[1:]:
    a, n, s, cr, ce = (l.split("\t") + [""] * 5)[:5]
    fn[a] = (n, int(s))
names = {}
for l in open(os.path.join(ROOT, "re/names.tsv")).read().splitlines()[1:]:
    p = (l.split("\t") + [""] * 5)[:5]
    names[p[0]] = p[1:]
rows = []
counts = {"verified": 0, "ported": 0, "platform": 0, "named": 0, "library": 0, "unnamed": 0}
for a, (gname, size) in sorted(fn.items()):
    if a in names:
        name, conf, status, desc = names[a]
    elif not gname.startswith("FUN_"):
        name, conf, status, desc = gname, "high", "library", "CRT, import thunk or exception handler (named by Ghidra)"
    else:
        name, conf, status, desc = "", "", "unnamed", ""
    counts[status] = counts.get(status, 0) + 1
    rows.append(f"| `{a}` | {size} | {name} | {conf} | {status} | {desc} |")
for a in sorted(set(names) - set(fn)):
    name, conf, status, desc = names[a]
    counts[status] = counts.get(status, 0) + 1
    rows.append(f"| `{a}` | ? | {name} | {conf} | {status} | {desc} (not found by Ghidra's analysis) |")
rows.sort()
total = sum(counts.values())
out = [
    "# Function map of lf2.exe (v2.0a)",
    "",
    "Generated by `tools/re/gen_function_map.py` from the Ghidra export and `re/names.tsv`.",
    "",
    "Status: **verified** means ported and matched against the running original (a trace in",
    "`traces/` passes through it, or a memory-dump test covers it); not every branch of a",
    "verified function has been exercised. **ported** means ported to Rust but not yet",
    "exercised by a trace. **named** means understood well enough to name; not ported.",
    "**platform** means Win32, DirectDraw, DirectSound or DirectShow code whose job the",
    "app does with its own window, renderer and sound (lf2-app, lf2-web).",
    "**library** means CRT code, an import thunk, an exception handler, or zlib (replaced",
    "by `lf2-data/src/flate.rs`).",
    "",
    "| status | functions |",
    "|---|---|",
] + [f"| {k} | {v} |" for k, v in counts.items()] + [
    f"| total | {total} |",
    "",
    "| address | size | name | confidence | status | description |",
    "|---|---|---|---|---|---|",
] + rows
open(os.path.join(ROOT, "docs/function-map.md"), "w").write("\n".join(out) + "\n")
print(counts, total)
