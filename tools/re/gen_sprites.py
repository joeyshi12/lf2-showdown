#!/usr/bin/env python3
"""Generate crates/lf2-sim/src/menu/sprites.rs from the menu set-up block of 0x4246b0:
which global holds the surface made from which RT_BITMAP resource, and the clip
rectangles (x at +0x10, y at +0x7e0, w at +0xfb0, h at +0x1780, 500 each) and the
clip count (+0xc) the code writes into each surface. The WORDS0..5 fonts, filled in
a loop, get their 256 cells generated here as the loop computes them.

usage: gen_sprites.py   (reads re/out/decomp/004246b0.c)
"""
import os, re, subprocess, sys
root = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..")
src = subprocess.run([sys.executable, os.path.join(root, "tools/re/simplify.py"),
                      os.path.join(root, "re/out/decomp/004246b0.c")], capture_output=True, text=True).stdout
start = src.index("if (DAT_0044d068 != 0)")
end = src.index("load_controls();", start)
block = src[start:end]
names = {}
for m in re.finditer(r'(DAT_[0-9a-f]+) =\s*(?:\([^)]*\))?surface_from_bitmap\([^,]+,0x40,"([A-Z0-9_]+)",0\)', block):
    names[m[1]] = m[2]
clips = {}
counts = {}
pat = re.compile(r'\*\(undefined4 \*\)\(\(?(?:int\))?(DAT_[0-9a-f]+) \+ (0x[0-9a-f]+|\d+)\) = (0x[0-9a-f]+|\d+);')
for m in pat.finditer(block):
    g, off, v = m[1], int(m[2], 0), int(m[3], 0)
    if v >= 0x80000000:
        v -= 1 << 32
    if off == 0xc:
        counts[g] = v
        continue
    for k, base in enumerate((0x10, 0x7e0, 0xfb0, 0x1780)):
        if base <= off < base + 2000:
            clips.setdefault(g, {}).setdefault((off - base) // 4, [0, 0, 0, 0])[k] = v
words = ["DAT_0044faf4", "DAT_0044f888", "DAT_0044fcbc", "DAT_0044fb68", "DAT_0044faf8", "DAT_0044fd80"]
for g in words:
    clips[g] = {i: [(i & 15) << 4, (i & ~15) + 1, 8, 16] for i in range(256)}
out = ["//! Generated by tools/re/gen_sprites.py from the menu set-up of 0x4246b0. Do not edit.",
       "//! Each sheet: the global that holds its surface, the RT_BITMAP resource it is made",
       "//! from, the clip count the code sets, and the clip rectangles (x, y, w, h).", "",
       "pub struct Sheet {", "    pub global: u32,", "    pub resource: &'static str,",
       "    pub count: i32,", "    pub clips: &'static [(i32, i32, i32, i32)],", "}", "",
       "pub const SHEETS: &[Sheet] = &["]
for g in sorted(names, key=lambda g: names[g]):
    cl = clips.get(g, {})
    n = max(cl) + 1 if cl else 0
    rows = ", ".join("(%d, %d, %d, %d)" % tuple(cl.get(i, [0, 0, 0, 0])) for i in range(n))
    out.append(f'    Sheet {{ global: 0x{g[4:]}, resource: "{names[g]}", count: {counts.get(g, 0)}, clips: &[{rows}] }},')
out.append("];")
dst = os.path.join(root, "crates/lf2-sim/src/menu/sprites.rs")
os.makedirs(os.path.dirname(dst), exist_ok=True)
open(dst, "w").write("\n".join(out) + "\n")
print("wrote", dst, len(names), "sheets")
for g in sorted(names): print(" ", g, names[g], counts.get(g), len(clips.get(g, {})))
