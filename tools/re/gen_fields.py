#!/usr/bin/env python3
"""Generate crates/lf2-sim/src/fields.rs from re/types.txt (struct Object) and
re/globals.tsv, so that the Rust code and the Ghidra project use the same names.

usage: gen_fields.py   (run from anywhere; paths are relative to the repository)
"""
import os, re

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..")
TYPES = os.path.join(ROOT, "re", "types.txt")
GLOBALS = os.path.join(ROOT, "re", "globals.tsv")
OUT = os.path.join(ROOT, "crates", "lf2-sim", "src", "fields.rs")

RUST = {"int": ("i32", "i32"), "uint": ("u32", "u32"), "char": ("i8", "i8"), "uchar": ("u8", "u8"),
        "byte": ("u8", "u8"), "double": ("f64", "f64")}


def struct_fields(name):
    out, cur = [], None
    for line in open(TYPES):
        f = line.split("#")[0].split()
        if not f:
            continue
        if f[0] == "struct":
            cur = f[1]
            continue
        if f[0] == "end":
            cur = None
            continue
        if cur == name:
            out.append((int(f[0], 0), f[1], f[2]))
    return out


def accessors(fields, recv, addr):
    lines = []
    for off, ty, name in fields:
        if ty not in RUST:
            continue
        rt, m = RUST[ty]
        a = addr(off)
        lines.append(f"    /// @{off:#x}\n    #[inline]\n    pub fn {name}(&self) -> {rt} {{ self.{recv}.{m}({a}) }}")
        lines.append(f"    #[inline]\n    pub fn set_{name}(&mut self, v: {rt}) {{ self.{recv}.set_{m}({a}, v) }}")
        if rt == "i32":
            lines.append(f"    #[inline]\n    pub fn add_{name}(&mut self, d: i32) {{ self.{recv}.add_i32({a}, d) }}")
    return "\n".join(lines)


def main():
    obj = struct_fields("Object")
    glob = []
    if os.path.exists(GLOBALS):
        for line in open(GLOBALS):
            if line.startswith("#") or line.startswith("address") or not line.strip():
                continue
            a, ty, name = line.rstrip("\n").split("\t")[:3]
            glob.append((int(a, 16), ty, name))
    src = [
        "//! Generated by tools/re/gen_fields.py from re/types.txt and re/globals.tsv.",
        "//! Do not edit by hand.",
        "#![allow(dead_code)]",
        "",
        "use crate::mem::Mem;",
        "",
        "/// A game object image (0x420 bytes).",
        "#[derive(Clone, PartialEq)]",
        "pub struct Obj {",
        "    pub m: Mem,",
        "}",
        "",
        "impl Obj {",
        "    pub fn new() -> Self { Obj { m: Mem::new(0, 0x420) } }",
        accessors(obj, "m", lambda o: f"{o:#x}"),
        "}",
        "",
        "/// The global variables (.data and .bss, 0x44d000..0x45a000).",
        "#[derive(Clone, PartialEq)]",
        "pub struct Globals {",
        "    pub m: Mem,",
        "}",
        "",
        "pub const GLOBALS_BASE: u32 = 0x44d000;",
        "pub const GLOBALS_LEN: usize = 0xd000;",
        "",
        "impl Globals {",
        "    pub fn new() -> Self { Globals { m: Mem::new(GLOBALS_BASE, GLOBALS_LEN) } }",
        accessors(glob, "m", lambda a: f"{a:#x}"),
        "}",
        "",
        "/// Names of global addresses, for reports.",
        "pub const GLOBAL_NAMES: &[(u32, &str)] = &[",
    ]
    src += [f"    ({a:#x}, \"{n}\")," for a, _, n in glob]
    src += ["];", "", "/// Names of object fields, for reports.", "pub const OBJECT_FIELDS: &[(u32, &str, &str)] = &["]
    src += [f"    ({o:#x}, \"{t}\", \"{n}\")," for o, t, n in obj]
    src += ["];", ""]
    open(OUT, "w").write("\n".join(src))
    print("wrote", OUT, len(obj), "object fields,", len(glob), "globals")


if __name__ == "__main__":
    main()
